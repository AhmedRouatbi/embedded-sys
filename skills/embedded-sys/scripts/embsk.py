# picocom/miniterm never exit, so an agent can't use them in a tool call. `embsk uart` is one bounded,
# scriptable session: send commands, wait for reply patterns, stop. Serial port (pyserial, else POSIX
# termios) or a process's stdin/stdout (--exec: a native_sim SIL build).
UART_USAGE = """usage: embsk uart [--port P] [--baud N] [--exec "CMD"] [--log FILE] STEPS...
  --timeout S  seconds each --expect may wait (default 10); anywhere on the command line
  steps run in order:  --send TEXT | --expect REGEX | --sleep S | --fail-on REGEX | --script FILE
  --send       write TEXT + CR (what a terminal sends on Enter)
  --expect     wait until a line received AFTER the last --send matches REGEX (re.search), else fail
  --fail-on    fail at once if any later line matches REGEX (e.g. 'ASSERT|FATAL')
  --script     steps from a file, one per line: send|expect|sleep|fail-on <arg>, or timeout <s> (applies to the
               expects after it); '#' lines are comments
  no steps     listen for --timeout seconds
  exit: 0 every expect matched · 1 timeout / fail-on / target gone · 2 bad usage or port"""


class _Term:
    """Raw terminal stream -> clean lines: UTF-8, colours dropped, and the cursor moves the Zephyr shell
    uses to redraw its prompt around log lines (CR, BS, ESC[nD, ESC[nC, ESC[J/K) applied."""

    def __init__(self):
        import codecs
        self.dec, self.line, self.cur, self.esc = codecs.getincrementaldecoder("utf-8")("replace"), [], 0, ""

    def feed(self, data):
        out = []
        for ch in self.dec.decode(data):
            if self.esc:
                self.esc += ch
                if len(self.esc) == 2 and ch != "[" or len(self.esc) > 32:  # two-byte escape, or junk
                    self.esc = ""
                elif len(self.esc) > 2 and "@" <= ch <= "~":
                    p = self.esc[2:-1]
                    n = int(p) if p.isdigit() else 1
                    if ch == "D":
                        self.cur = max(0, self.cur - n)
                    elif ch == "C":
                        self.cur += n
                    elif ch in "JK":
                        del self.line[self.cur:]
                    self.esc = ""
            elif ch == "\x1b":
                self.esc = ch
            elif ch == "\n":
                out.append("".join(self.line).rstrip())
                self.line, self.cur = [], 0
            elif ch == "\r":
                self.cur = 0
            elif ch == "\b":
                self.cur = max(0, self.cur - 1)
            elif ch >= " " or ch == "\t":
                self.line += [" "] * (self.cur - len(self.line))
                if self.cur < len(self.line):
                    self.line[self.cur] = ch
                else:
                    self.line.append(ch)
                self.cur += 1
        return out


class _Exec:
    """A process as the target: its stdin is the UART RX, stdout+stderr the TX."""

    def __init__(self, cmd):
        import queue, shlex, threading
        self.q = queue.Queue()
        self.p = subprocess.Popen(shlex.split(cmd, posix=not WIN), cwd=root(), stdin=subprocess.PIPE,
                                  stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
        threading.Thread(target=self._pump, daemon=True).start()

    def _pump(self):
        while True:
            b = self.p.stdout.read1(4096)
            self.q.put(b or None)
            if not b:
                return

    def read(self, t):
        import queue
        try:
            b = self.q.get(timeout=max(t, 0.001))
        except queue.Empty:
            return b""
        if b is None:
            raise EOFError(f"target exited (code {self.p.wait()})")
        return b

    def write(self, b):
        try:
            self.p.stdin.write(b)
            self.p.stdin.flush()
        except OSError as e:
            raise EOFError(f"target exited ({e})")

    def close(self):
        if self.p.poll() is None:
            self.p.terminate()
            try:
                self.p.wait(3)
            except subprocess.TimeoutExpired:
                self.p.kill()


class _Pyserial:
    def __init__(self, port, baud):
        import serial
        self.s = serial.Serial(port, baud, timeout=0)

    def read(self, t):
        self.s.timeout = t
        b = self.s.read(1)
        return b + self.s.read(self.s.in_waiting) if b else b

    def write(self, b):
        self.s.write(b)
        self.s.flush()

    def close(self):
        self.s.close()


class _Termios:
    """POSIX serial port (or pty) without pyserial: raw mode, 8N1."""

    def __init__(self, port, baud):
        import termios, tty
        speed = getattr(termios, f"B{baud}", None)
        if speed is None:
            raise OSError(f"baud {baud} not supported by termios (install pyserial)")
        self.fd = os.open(port, os.O_RDWR | os.O_NOCTTY | os.O_NONBLOCK)
        tty.setraw(self.fd)
        a = termios.tcgetattr(self.fd)
        a[2] |= termios.CLOCAL | termios.CREAD
        a[4] = a[5] = speed
        termios.tcsetattr(self.fd, termios.TCSANOW, a)

    def read(self, t):
        import select
        if not select.select([self.fd], [], [], t)[0]:
            return b""
        try:
            b = os.read(self.fd, 4096)
        except BlockingIOError:
            return b""
        except OSError as e:  # pty peer closed / USB unplugged
            raise EOFError(f"port closed ({e})")
        if not b:
            raise EOFError("port closed")
        return b

    def write(self, b):
        import select
        while b:
            select.select([], [self.fd], [], 1)
            try:
                b = b[os.write(self.fd, b):]
            except BlockingIOError:
                pass

    def close(self):
        os.close(self.fd)


class _UartFail(Exception):
    pass


def _uart_script(path):
    steps = []
    for n, raw in enumerate(Path(path).read_text(encoding="utf-8").splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        verb, _, arg = line.partition(" ")
        if verb not in ("send", "expect", "sleep", "timeout", "fail-on"):
            raise ValueError(f"{path}:{n}: unknown step '{verb}' (send|expect|sleep|timeout|fail-on)")
        steps.append((verb, arg.strip()))
    return steps


def uart(prof, args):
    """Bounded UART session for agents: ordered send/expect steps, clean transcript in artifacts/uart.txt."""
    import time
    from datetime import datetime
    steps, port, baud, exe, log, a = [], prof.get("serial_port") or "", 115200, None, root() / "artifacts" / "uart.txt", ""
    it = iter(args)
    try:
        for a in it:
            if a in ("--send", "--expect", "--sleep", "--fail-on"):
                steps.append((a[2:], next(it)))
            elif a == "--timeout":  # a default, wherever it is given
                steps.insert(0, ("timeout", next(it)))
            elif a == "--script":
                steps += _uart_script(next(it))
            elif a == "--port":
                port = next(it)
            elif a == "--baud":
                baud = int(next(it))
            elif a == "--exec":
                exe = next(it)
            elif a == "--log":
                log = Path(next(it))
            else:
                print(UART_USAGE)
                return 0 if a in ("-h", "--help") else 2
        for verb, v in steps:
            if verb in ("sleep", "timeout"):
                float(v)
            elif verb in ("expect", "fail-on"):
                re.compile(v)
    except StopIteration:
        print(f"embsk uart: {a} needs a value\n{UART_USAGE}")
        return 2
    except (ValueError, OSError, re.error) as e:
        print(f"embsk uart: {e}")
        return 2
    if not any(v in ("send", "expect", "sleep") for v, _ in steps):
        steps.append(("sleep", next((x for v, x in reversed(steps) if v == "timeout"), "10")))
    try:
        if exe:
            link, target = _Exec(exe), f"exec {exe}"
        else:
            if not port:
                print("embsk uart: no port (embsk set serial_port=... or --port)")
                return 2
            try:
                link = _Pyserial(port, baud)
            except ImportError:
                if WIN:
                    print("embsk uart needs pyserial on Windows: py -3 -m pip install --user pyserial")
                    return 2
                link = _Termios(port, baud)
            target = f"{port} @ {baud}"
    except (OSError, ValueError) as e:  # serial.SerialException is an OSError
        print(f"embsk uart: cannot open {exe or port}: {e}")
        return 2

    log.parent.mkdir(parents=True, exist_ok=True)
    fh = log.open("a", encoding="utf-8")
    fh.write(f"\n# embsk uart {datetime.now().isoformat(timespec='seconds')} {target}\n")
    term, pending, fail_on, timeout, ok, t0 = _Term(), [], [], 10.0, 0, time.monotonic()

    def note(m):
        print(f">> {m}", flush=True)
        fh.write(f">> {m}\n")

    def pump(t):
        new = term.feed(link.read(t))
        for line in new:
            print(line, flush=True)
            fh.write(line + "\n")
            hit = next((rx for rx in fail_on if rx.search(line)), None)
            if hit:
                raise _UartFail(f"fail-on /{hit.pattern}/ matched: {line}")
        pending.extend(new)
        return new

    rc, total = 0, sum(v == "expect" for v, _ in steps)
    try:
        for i, (verb, arg) in enumerate(steps, 1):
            if verb == "timeout":
                timeout = float(arg)
            elif verb == "fail-on":
                fail_on.append(re.compile(arg))
            elif verb == "sleep":
                end = time.monotonic() + float(arg)
                while time.monotonic() < end:
                    pump(min(end - time.monotonic(), 0.2))
            elif verb == "send":
                while pump(0.05):  # drain: output from before the command must not satisfy the next expect
                    pass
                pending.clear()
                note(f"send: {arg}")
                link.write((arg + "\r").encode())
            elif verb == "expect":
                rx, end = re.compile(arg), time.monotonic() + timeout
                while True:
                    k = next((k for k, line in enumerate(pending) if rx.search(line)), None)
                    if k is not None:
                        del pending[:k + 1]
                        ok += 1
                        note(f"ok: /{arg}/")
                        break
                    if time.monotonic() >= end:
                        raise _UartFail(f"TIMEOUT: no line matched /{arg}/ within {timeout:g} s (step {i})")
                    pump(min(end - time.monotonic(), 0.2))
    except (_UartFail, EOFError) as e:
        note(f"FAIL {e}")
        rc = 1
    except KeyboardInterrupt:
        rc = 1
    finally:
        link.close()
        note(f"{ok}/{total} expects matched in {time.monotonic() - t0:.1f} s; transcript: {log}")
        fh.close()
    return rc


# ---------------------------------------------------------------- curses menu
def menu():
    try:
        import curses
    except ImportError:  # CPython on Windows ships no curses
        print("embsk menu needs curses. Windows: python -m pip install --user windows-curses (install.py does it).\n"
              "Without a menu: embsk set board=... debugger=... (or /embsk in Claude Code: checkbox questions).")
        return 2
    prof, index = load(), None

    def rows():
        out = []
        for label, key, typ, vals, when in OPTIONS:
            if not visible(prof, when):
                continue
            if typ == "multi":
                out.append(("hdr", label, None, None))
                out += [("feat", f, key, f) for f in vals]
            else:
                out.append((typ, label, key, vals))
        return out

    def show(typ, key, vals):
        v = prof.get(key)
        if typ == "bool":
            return "[x]" if v else "[ ]"
        if typ in ("choice", "level"):
            return f"< {v} >"
        if key == "mcu" and prof["platform"] == "zephyr" and not v:
            return "(from board)"
        if typ == "list":
            return ",".join(v) or "(none)"
        return v or "(enter to set)"

    def cycle(typ, key, vals, step):
        if typ == "choice":
            prof[key] = vals[(vals.index(prof[key]) + step) % len(vals)] if prof[key] in vals else vals[0]
            if key == "platform" and prof["platform"] == "zephyr":
                prof["tests"] = "ztest"
            normalize(prof)
        elif typ == "level":
            lv = LEVELS[prof["safety"]]
            prof[key] = lv[(lv.index(prof[key]) + step) % len(lv)] if prof[key] in lv else lv[0]
        elif typ == "bool":
            prof[key] = not prof[key]

    def readkey(scr):
        """get_wch + manual decode of CSI/SS3 arrows (some terminals/multiplexers send them raw)."""
        k = scr.get_wch()
        if k != "\x1b":
            return k
        scr.nodelay(True)
        try:
            a, b = scr.get_wch(), scr.get_wch()
            return {"A": curses.KEY_UP, "B": curses.KEY_DOWN, "C": curses.KEY_RIGHT, "D": curses.KEY_LEFT}.get(b, "\x1b") if a in ("[", "O") else "\x1b"
        except curses.error:
            return "\x1b"
        finally:
            scr.nodelay(False)

    def prompt(scr, text, init=""):
        h, w = scr.getmaxyx()
        scr.move(h - 1, 0); scr.clrtoeol(); scr.addstr(h - 1, 0, text[: w - 1], curses.A_BOLD)
        curses.echo(); curses.curs_set(1)
        s = scr.getstr(h - 1, min(len(text), w - 2), 120).decode(errors="ignore").strip()
        curses.noecho(); curses.curs_set(0)
        return s or init

    def pick_board(scr):
        nonlocal index
        if index is None:
            scr.addstr(0, 0, "indexing Zephyr boards..."); scr.refresh()
            index = board_index(prof)
            if not index:
                return
        q, sel = prof.get("mcu", "") if not prof["board"] else "", 0
        while True:
            hits = search(index, q)
            h, w = scr.getmaxyx()
            scr.erase()
            scr.addstr(0, 0, f"Board search (name / identifier / MCU): {q}"[: w - 1], curses.A_BOLD)
            scr.addstr(1, 0, f"{len(hits)} matches  - type to filter, Up/Down, Enter select, Esc cancel"[: w - 1], curses.A_DIM)
            top = max(0, sel - (h - 4))
            for i, b in enumerate(hits[top: top + h - 3]):
                line = f"{b['id']:<42} {'/'.join(b['socs']):<16} {b['arch']:<7} {b['full_name']}"
                scr.addstr(2 + i, 0, line[: w - 1], curses.A_REVERSE if top + i == sel else 0)
            k = readkey(scr)
            if k in ("\x1b",):
                return
            if k in ("\n", "\r", curses.KEY_ENTER) and hits:
                prof["board"] = hits[sel]["id"]
                if not prof["mcu"] or not any(soc_match(prof["mcu"], s) for s in hits[sel]["socs"]):
                    prof["mcu"] = hits[sel]["socs"][0] if hits[sel]["socs"] else ""
                return
            if k == curses.KEY_UP: sel = max(0, sel - 1)
            elif k == curses.KEY_DOWN: sel = min(len(hits) - 1, sel + 1)
            elif k in (curses.KEY_BACKSPACE, "\x7f", "\b"): q, sel = q[:-1], 0
            elif isinstance(k, str) and k.isprintable(): q, sel = q + k, 0

    def main(scr):
        curses.curs_set(0)
        cur, msg = 0, "Up/Down move · Left/Right/Space change · Enter edit/search · s save · q quit"
        while True:
            R = rows()
            cur = min(cur, len(R) - 1)
            while R[cur][0] == "hdr":
                cur += 1
            h, w = scr.getmaxyx()
            scr.erase()
            scr.addstr(0, 0, f" embsk - embedded profile  [{root()}]"[: w - 1], curses.A_BOLD | curses.A_REVERSE)
            top = max(0, cur - (h - 5))
            for i, (typ, label, key, vals) in enumerate(R[top: top + h - 4]):
                y, sel = 1 + i, (top + i == cur)
                if typ == "hdr":
                    scr.addstr(y, 0, f" -- {label} --"[: w - 1], curses.A_DIM)
                elif typ == "feat":
                    mark = "[x]" if label in prof["features"] else "[ ]"
                    scr.addstr(y, 0, f"   {mark} {label}"[: w - 1], curses.A_REVERSE if sel else 0)
                else:
                    scr.addstr(y, 0, f" {'>' if sel else ' '} {label:<28} {show(typ, key, vals)}"[: w - 1], curses.A_REVERSE if sel else 0)
            scr.addstr(h - 2, 0, msg[: w - 1], curses.A_DIM)
            k = readkey(scr)
            typ, label, key, vals = R[cur]
            if k in ("q", "\x1b"):
                return False
            if k == "s":
                errs = [m for lv, m in doctor(prof, index) if lv == "ERR"]
                if errs and prompt(scr, f"{len(errs)} error(s): {errs[0][:70]}  save anyway? [y/N] ").lower() != "y":
                    msg = "ERR: " + " | ".join(errs)
                    continue
                return True
            if k == curses.KEY_UP:
                cur = max(0, cur - 1)
                while R[cur][0] == "hdr" and cur > 0:
                    cur -= 1
            elif k == curses.KEY_DOWN:
                cur = min(len(R) - 1, cur + 1)
            elif typ == "feat" and k in (" ", "\n", "\r", curses.KEY_LEFT, curses.KEY_RIGHT):
                f = prof["features"]
                prof["features"] = [x for x in f if x != label] if label in f else f + [label]
            elif typ in ("choice", "level", "bool") and k in (" ", "\n", "\r", curses.KEY_RIGHT, curses.KEY_LEFT):
                cycle(typ, key, vals, -1 if k == curses.KEY_LEFT else 1)
            elif typ == "board" and k in ("\n", "\r", " "):
                pick_board(scr)
            elif typ == "text" and k in ("\n", "\r", " "):
                prof[key] = prompt(scr, f"{label}: ", prof.get(key, ""))
            elif typ == "list" and k in ("\n", "\r", " "):
                prof[key] = coerce(key, prompt(scr, f"{label} (comma separated): ", ",".join(prof.get(key, []))))
            if typ in ("board", "text") and key in ("board", "mcu"):
                bad = [m for lv, m in doctor(prof, index) if lv == "ERR" and ("Board" in m or "MCU" in m or "Probe" in m)] if index is not None else []
                msg = ("ERR: " + bad[0]) if bad else "Up/Down move · Left/Right/Space change · Enter edit/search · s save · q quit"

    if curses.wrapper(main):
        save(normalize(prof))
        f = render(prof)
        print(f"saved {root() / '.embsk/profile.json'} and updated {f}")
        for lv, m in doctor(prof, index):
            print(f"  {lv:<4} {m}")
        if prof["platform"] == "zephyr" and prof["board"] and sys.stdin.isatty():
            if input("\nSet up the west workspace (only the modules this board needs) and build now? [Y/n] ").strip().lower() in ("", "y", "yes"):
                return setup(prof, [])
    else:
        print("cancelled, nothing saved")


