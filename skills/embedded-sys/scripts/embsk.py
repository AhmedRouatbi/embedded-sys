def west_ws():
    """West workspace containing the project -> {"top", "manifest", "zephyr"} or None."""
    import configparser
    for d in [root(), *root().parents]:
        cfg = d / ".west" / "config"
        if cfg.exists():
            c = configparser.ConfigParser()
            c.read(cfg)
            base = c.get("zephyr", "base", fallback=None)
            zephyr = d / base if base else next((d / x for x in ("deps/zephyr", "zephyr") if (d / x / "VERSION").exists()), d / "deps/zephyr")
            return {"top": d, "manifest": c.get("manifest", "path", fallback=""), "zephyr": zephyr}
    return None


def zephyr_base(prof):
    """profile override > the project's own west workspace > $ZEPHYR_BASE > ~/zephyrproject (reference tree)."""
    if prof.get("zephyr_base"):
        return Path(prof["zephyr_base"]).expanduser()
    ws = west_ws()
    if ws and (ws["zephyr"] / "VERSION").exists():
        return ws["zephyr"]
    if os.environ.get("ZEPHYR_BASE"):
        return Path(os.environ["ZEPHYR_BASE"])
    home = Path.home() / "zephyrproject" / "zephyr"
    return home if home.exists() else None


def _runners(board_dir):
    found, cm = set(), board_dir / "board.cmake"
    if cm.exists():
        txt = cm.read_text(errors="ignore")
        found |= {re.sub(r"-(stm32|nrf5)$", "", n) for n in re.findall(r"boards/common/([\w-]+)\.board\.cmake", txt)}
        found |= set(re.findall(r"board_set_(?:flasher|debugger)_ifnset\((\w+)\)", txt))
        found |= set(re.findall(r"board_runner_args\(\s*([\w-]+)", txt))
    return sorted(found)


def _board_entries(txt):
    """board.yml -> [(name, full_name, vendor, [socs])]. PyYAML ships with every Zephyr venv."""
    try:
        import yaml
        data = yaml.safe_load(txt) or {}
        ents = data.get("boards") or ([data["board"]] if isinstance(data.get("board"), dict) else [])
        return [(e["name"], e.get("full_name", ""), e.get("vendor", ""), [s["name"] for s in e.get("socs", []) if "name" in s])
                for e in ents if isinstance(e, dict) and "name" in e]
    except ImportError:  # shortcut: no PyYAML -> first name only, no SoC matching; install pyyaml to upgrade
        m = re.search(r"name:\s*['\"]?([\w.-]+)", txt)
        return [(m.group(1), "", "", [])] if m else []


_INDEX = {}


def board_index(prof):
    zb = zephyr_base(prof)
    roots = ([zb / "boards"] if zb else []) + [Path(r).expanduser() / "boards" for r in prof.get("board_root", [])]
    key = tuple(map(str, roots))
    if key in _INDEX:
        return _INDEX[key]
    out = _INDEX[key] = []
    for broot in roots:
        for byml in broot.rglob("board.yml") if broot.exists() else []:
            d = byml.parent
            runners = _runners(d)
            for name, full, vendor, socs in _board_entries(byml.read_text(errors="ignore")):
                ids = []
                for y in d.glob("*.yaml"):
                    yt = y.read_text(errors="ignore")
                    im = re.search(r"^identifier:\s*(\S+)", yt, re.M)
                    if im and (im.group(1) == name or im.group(1).startswith(name + "/")):
                        g = lambda k: (re.search(rf"^{k}:\s*(\S+)", yt, re.M) or [None, ""])[1]
                        ids.append({"id": im.group(1), "arch": g("arch"), "ram": g("ram"), "flash": g("flash")})
                if not ids:
                    ids = [{"id": name, "arch": "", "ram": "", "flash": ""}]
                for i in ids:
                    out.append({**i, "name": name, "full_name": full, "vendor": vendor, "socs": socs, "runners": runners, "dir": str(d)})
    return out


def soc_match(mcu, soc):
    """stm32f401ret6 ~ stm32f401xe (x = wildcard); partial mcu 'stm32f401' matches too."""
    mcu, soc = mcu.lower().replace("-", "").replace("_", ""), soc.lower().replace("_", "")
    if not mcu:
        return False
    if soc.startswith(mcu):
        return True
    return len(mcu) >= len(soc) and all(s in ("x", c) for s, c in zip(soc, mcu[: len(soc)]))


def search(index, q):
    q = q.lower().strip()
    if not q:
        return index
    hit = [b for b in index if q in b["id"].lower() or q in b["full_name"].lower() or any(soc_match(q, s) for s in b["socs"])]
    return sorted(hit, key=lambda b: (b["id"] != q, not b["id"].startswith(q), b["id"]))


def find_board(index, board):
    exact = [b for b in index if b["id"] == board]
    return exact or [b for b in index if b["name"] == board]


