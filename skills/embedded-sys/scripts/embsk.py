def jlink_device(prof):
    """J-Link device string from the board's board.cmake (--device=...), matched to the cpu cluster."""
    hits = find_board(board_index(prof), prof["board"]) if prof["board"] else []
    cm = Path(hits[0]["dir"]) / "board.cmake" if hits else None
    devs = re.findall(r'--device=([^"\s]+)', cm.read_text(errors="ignore")) if cm and cm.exists() else []
    cluster = prof["board"].split("/")[2] if prof["board"].count("/") >= 2 else ""
    return next((d for d in devs if cluster and d.lower().endswith(cluster.replace("cpu", ""))), devs[0] if devs else None)


