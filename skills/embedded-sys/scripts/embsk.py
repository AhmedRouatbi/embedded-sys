def which_any(names):
    return next((n for n in names if shutil.which(n) or any(p.exists() for p in TOOL_FALLBACK.get(n, []))), None)


def openocd_target_dir():
    exe = shutil.which("openocd")
    for c in ([Path(exe).resolve().parent.parent / "share" / "openocd" / "scripts" / "target"] if exe else []) + [Path("/usr/share/openocd/scripts/target"), Path("/usr/local/share/openocd/scripts/target")]:
        if c.is_dir():
            return c
    return None


def openocd_target(mcu):
    m = mcu.lower()
    for pat, cfg in [(r"stm32([a-z]{1,2}\d)", lambda g: f"stm32{g}x.cfg"), (r"(nrf5\d|nrf91)", lambda g: f"{g}.cfg"), (r"(rp2040|rp2350)", lambda g: f"{g}.cfg"),
                     (r"(max\d{5})", lambda g: f"{g}.cfg"), (r"(esp32\w*)", lambda g: f"{g}.cfg"), (r"(at?samd\d+|atsame\d+)", lambda g: "at91samdXX.cfg")]:
        mm = re.search(pat, m)
        if mm:
            return cfg(mm.group(1))
    return None


def doctor(prof, index=None):
    """-> list of (level, message). level: ERR | WARN | OK"""
    r, plat, dbg = [], prof["platform"], prof["debugger"]
    if plat == "zephyr":
        zb = zephyr_base(prof)
        if not zb or not (zb / "VERSION").exists():
            r.append(("ERR", "Zephyr tree not found: set ZEPHYR_BASE, run inside a west workspace, or `embsk set zephyr_base=<path>`"))
        else:
            v = dict(re.findall(r"(\w+)\s*=\s*(\S*)", (zb / "VERSION").read_text()))
            r.append(("OK", f"Zephyr {v.get('VERSION_MAJOR')}.{v.get('VERSION_MINOR')}.{v.get('PATCHLEVEL')}{('-' + v['EXTRAVERSION']) if v.get('EXTRAVERSION') else ''} at {zb}"))
            index = index if index is not None else board_index(prof)
            hits = find_board(index, prof["board"]) if prof["board"] else []
            if not prof["board"]:
                r.append(("ERR", "No Zephyr board chosen (Alt+A -> Zephyr board, or `embsk boards <mcu>`)"))
            elif not hits:
                sug = ", ".join(b["id"] for b in search(index, prof["board"].split("/")[0])[:5])
                r.append(("ERR", f"Board '{prof['board']}' does not exist in this Zephyr tree" + (f". Close: {sug}" if sug else "")))
            elif len(hits) > 1 and hits[0]["id"] != prof["board"]:
                r.append(("ERR", f"Board '{prof['board']}' needs qualifiers, pick one: {', '.join(h['id'] for h in hits)}"))
            else:
                b = hits[0]
                r.append(("OK", f"Board {b['id']} ({b['full_name']}) SoC {'/'.join(b['socs'])} arch {b['arch'] or '?'} RAM {b['ram'] or '?'}K flash {b['flash'] or '?'}K"))
                if prof["mcu"] and not any(soc_match(prof["mcu"], s) for s in b["socs"]):
                    r.append(("ERR", f"MCU '{prof['mcu']}' does not match board SoC {'/'.join(b['socs'])} — fix MCU or pick another board"))
                if dbg != "none" and b["runners"] and not set(RUNNERS.get(dbg, [])) & set(b["runners"]):
                    r.append(("ERR", f"Probe '{dbg}' is not a runner for {b['name']}; board supports: {', '.join(b['runners'])}"))
                elif dbg != "none":
                    r.append(("OK", f"Probe '{dbg}' supported by board (runners: {', '.join(b['runners']) or 'unknown'})"))
                if prof["toolchain"] == "zephyr-sdk" and b["arch"]:
                    sdk, ver = find_sdk(b["arch"])
                    e = os.environ.get("ZEPHYR_SDK_INSTALL_DIR")
                    if sdk is False:
                        r.append(("ERR", sdk_hint(ver)))
                    elif sdk:
                        r.append(("OK", f"Zephyr SDK {ver} at {sdk} (from PATH)"))
                        if e and Path(e).expanduser().resolve() not in (sdk, sdk.parent):
                            r.append(("WARN", f"ZEPHYR_SDK_INSTALL_DIR={e} is not the SDK on PATH; a fresh plain `west build` would use it — unset it or point it at {sdk}"))
        if not shutil.which("west"):
            r.append(("ERR", "`west` not on PATH (activate the Zephyr venv)"))
        if WIN and prof["host_board"].startswith("native_sim"):
            r.append(("WARN", "native_sim (host tests) builds on Linux only: run test_host in WSL, or set host_board to a QEMU board"))
    else:
        if not prof["mcu"]:
            r.append(("ERR", "Bare-metal/FreeRTOS needs an MCU name (e.g. STM32F401RE, nRF52840, RP2040)"))
        cc = CC.get(prof["toolchain"])
        if prof["toolchain"] == "zephyr-sdk":
            r.append(("WARN", "toolchain 'zephyr-sdk' on a non-Zephyr project: pick gnu-arm/llvm/iar/keil"))
        elif cc and not which_any(cc):
            r.append(("WARN", f"compiler {'/'.join(cc)} not on PATH"))
        if dbg == "openocd" and prof["mcu"]:
            cfg, tdir = openocd_target(prof["mcu"]), openocd_target_dir()
            if cfg and tdir and not (tdir / cfg).exists():
                r.append(("WARN", f"OpenOCD target/{cfg} not found in {tdir}; check `ls {tdir} | grep -i {prof['mcu'][:6].lower()}`"))
            elif cfg:
                r.append(("OK", f"OpenOCD target config: target/{cfg}"))
    if dbg != "none" and not which_any(TOOLS.get(dbg, [])):
        r.append(("WARN", f"probe tool for '{dbg}' not on PATH ({' or '.join(TOOLS.get(dbg, []))})"))
    if prof["log"] == "rtt" and dbg in ("stlink", "esptool", "blackmagic"):
        r.append(("WARN", f"RTT with '{dbg}' is awkward; prefer uart/swo or a J-Link/pyOCD/probe-rs/OpenOCD probe"))
    if prof["safety"] != "none":
        if prof["safety_level"] not in LEVELS[prof["safety"]]:
            r.append(("ERR", f"Integrity level '{prof['safety_level']}' invalid for {prof['safety']}: {', '.join(LEVELS[prof['safety']])}"))
        if prof["coding_standard"] == "none":
            r.append(("WARN", "Safety standard chosen but no coding standard: set misra-c-2012 or misra-c-2023"))
        if prof["ponytail"] == "ultra":
            r.append(("WARN", "ponytail=ultra on a safety project: use full (never cut defensive checks)"))
    if prof["graphify"] and not shutil.which("graphify"):
        r.append(("WARN", "graphify not installed: `uv tool install graphifyy` (falls back to rg)"))
    return r


