def manifest_projects(zb):
    """Module names Zephyr's own west.yml offers (what name-allowlist can select)."""
    f = Path(zb) / "west.yml"
    return set(re.findall(r"^\s*-\s*name:\s*([\w.-]+)", f.read_text(), re.M)) if f.exists() else set()


def soc_vendor(zb, socs):
    for y in (Path(zb) / "soc").rglob("soc.yml"):
        txt = y.read_text(errors="ignore")
        if any(re.search(rf"^\s*-\s*name:\s*['\"]?{re.escape(x)}['\"]?\s*$", txt, re.M) for x in socs):
            return y.relative_to(Path(zb) / "soc").parts[0]
    return None


def required_modules(prof, zb, index=None):
    """-> (sorted module list, notes) or (None, [reason]) when the board is unknown in tree zb."""
    hits = find_board(index if index is not None else board_index({**prof, "zephyr_base": str(zb)}), prof["board"]) if prof["board"] else []
    if not hits:
        return None, [f"board '{prof['board']}' not found in {zb}"]
    b, known, notes = hits[0], manifest_projects(zb), []
    vendor = soc_vendor(zb, b["socs"])
    hal = HAL.get(vendor, f"hal_{vendor}") if vendor else None
    mods = [hal] if hal in known else []  # derived name: silently skip vendors without a HAL module (native, qemu, ...)
    mods += ARCH_MODULES.get(b["arch"], []) + LOG_MODULES.get(prof["log"], []) + list(prof.get("extra_modules", []))
    mods += [m for f in prof["features"] for m in FEATURE_MODULES.get(f, [])]
    unknown = sorted({m for m in mods if m not in known})
    if unknown:
        notes.append(f"not in Zephyr's manifest, skipped: {', '.join(unknown)}")
    if "sensors" in prof["features"] and vendor == "st":
        notes.append("ST MEMS sensor drivers (lis2dh, lsm6dso, ...) need hal_st: embsk set extra_modules=hal_st")
    if b["id"].endswith("/ns"):
        notes.append("'/ns' targets build TF-M: add its modules via extra_modules (trusted-firmware-m, mbedtls-3.6, tf-psa-crypto)")
    return sorted({m for m in mods if m in known}), notes


def manifest_file(prof):
    return root() / (prof["app_dir"] or "app") / "west.yml"


def read_allowlist(prof):
    f = manifest_file(prof)
    if not f.exists():
        return None
    m = re.search(r"^(\s*)name-allowlist:[^\n]*\n((?:\1\s+-\s.*\n?)*)", f.read_text(), re.M)
    return [x for x in re.findall(r"-\s*([\w.-]+)", m.group(2)) if x != "none"] if m else None


def write_manifest(prof, mods):
    """Create app/west.yml, or patch its zephyr revision + name-allowlist in place. -> True if changed."""
    f, rev = manifest_file(prof), prof.get("zephyr_rev") or "v4.4.2"
    # An EMPTY allowlist means "no filter" to west (it would fetch every module), so an unknown
    # module list becomes the non-matching placeholder "none": Zephyr only, no modules.
    mods = list(mods) or ["none"]
    if not f.exists():
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(MANIFEST_TEMPLATE.format(url=ZEPHYR_URL, rev=rev, items="\n".join(f"          - {m}" for m in mods)))
        return True
    old = f.read_text()
    new = re.sub(r"(-\s*name:\s*zephyr\b[\s\S]*?\n\s*revision:\s*)(\S+)", lambda m: m.group(1) + rev, old, count=1)
    m = re.search(r"^(\s*)name-allowlist:[^\n]*\n((?:\1\s+-\s.*\n?)*)", new, re.M)
    if m is None:
        print(f"  !! {f.relative_to(root())} has no name-allowlist block; leaving it as is")
        return new != old and bool(f.write_text(new))
    ind = m.group(1) + "  "
    block = f"{m.group(1)}name-allowlist:\n" + "\n".join(f"{ind}- {x}" for x in mods) + "\n"
    new = new[: m.start()] + block + new[m.end():]
    if new != old:
        f.write_text(new)
    return new != old


def west_env(prof):
    """Env for west/cmake: our workspace's Zephyr wins over a global $ZEPHYR_BASE; project venv first on PATH."""
    env, ws = dict(os.environ), west_ws()
    if prof.get("zephyr_base"):
        env["ZEPHYR_BASE"] = str(Path(prof["zephyr_base"]).expanduser())
    elif ws:  # own/enclosing workspace: its Zephyr, or none yet (a global ZEPHYR_BASE would hijack west)
        if (ws["zephyr"] / "VERSION").exists():
            env["ZEPHYR_BASE"] = str(ws["zephyr"])
        else:
            env.pop("ZEPHYR_BASE", None)
    elif zephyr_base(prof):  # no workspace: build against a reference tree (e.g. ~/zephyrproject)
        env["ZEPHYR_BASE"] = str(zephyr_base(prof))
    sdk = sdk_from_path()
    if sdk:  # CMake ignores PATH when looking for the SDK: point it at the one the user put on PATH
        env["ZEPHYR_SDK_INSTALL_DIR"] = str(sdk)
    venv = venv_exe(root() / ".venv", "python").parent
    if venv.is_dir():
        env["PATH"] = f"{venv}{os.pathsep}{env.get('PATH', '')}"
        env["VIRTUAL_ENV"] = str(venv.parent)
    return env


def venv_exe(venv, name):
    """.venv/bin/<name> (POSIX) or .venv\\Scripts\\<name>.exe (Windows)."""
    return venv / ("Scripts" if WIN else "bin") / (name + (".exe" if WIN else ""))


def resolve(cmd, env):
    """Windows looks the executable up in OUR PATH, not the child's env: resolve it in env's PATH first."""
    return [shutil.which(cmd[0], path=env.get("PATH")) or cmd[0], *cmd[1:]]


def bash_exe():
    """bash for helper scripts. Windows: Git Bash (Pi / Claude Code search order), never WSL's System32 launcher."""
    if not WIN:
        return shutil.which("bash")
    git = shutil.which("git")
    cands = [os.environ.get("CLAUDE_CODE_GIT_BASH_PATH", ""),
             *(str(Path(os.environ[v]) / "Git" / "bin" / "bash.exe") for v in ("ProgramFiles", "ProgramFiles(x86)") if os.environ.get(v)),
             str(Path(git).resolve().parent.parent / "bin" / "bash.exe") if git else ""]
    hit = next((c for c in cands if c and Path(c).is_file()), None)
    b = shutil.which("bash")
    return hit or (b if b and "system32" not in b.lower() else None)


def sh(cmd, env=None, check=True):
    print(f"  $ {' '.join(cmd)}", flush=True)
    rc = subprocess.call(resolve(cmd, env or os.environ), cwd=root(), env=env)
    if rc and check:
        raise SystemExit(f"embsk setup: command failed (exit {rc}): {' '.join(cmd)}")
    return rc


def west_python(env):
    """Interpreter that runs west (cmake reuses it through WEST_PYTHON)."""
    exe = shutil.which("west", path=env.get("PATH"))
    if not exe:
        return None
    if WIN:  # west.exe is a pip launcher: its python.exe sits next to it (venv) or one level up (base install)
        return next((str(p) for p in (Path(exe).parent / "python.exe", Path(exe).parent.parent / "python.exe") if p.exists()), sys.executable)
    first = (Path(exe).read_text(errors="ignore").splitlines() or [""])[0] if Path(exe).is_file() else ""
    return first[2:].strip().split()[0] if first.startswith("#!") else sys.executable


def ensure_python(prof, zb=None):
    """west on PATH and Zephyr's build deps importable; otherwise create .venv in the workspace."""
    env = west_env(prof)
    py = west_python(env)
    need = "import elftools, yaml, pykwalify, jsonschema, packaging"
    if py and (zb is None or subprocess.call([py, "-c", need], stderr=subprocess.DEVNULL) == 0):
        return env
    venv = root() / ".venv"
    if not venv.exists():
        print("  creating .venv (west + Zephyr Python requirements, isolated from the system Python)")
        sh([sys.executable, "-m", "venv", str(venv)])
    pip = [str(venv_exe(venv, "python")), "-m", "pip", "install", "-q"]
    sh(pip + ["west"])
    req = Path(zb) / "scripts" / "requirements-base.txt" if zb else None
    if req and req.exists():
        sh(pip + ["-r", str(req)])
    return west_env(prof)


# The Zephyr SDK is a user prerequisite: installed outside the skill and found through PATH only.
# embsk never downloads or installs it.
def sdk_from_path():
    """Root (dir with sdk_version) of the Zephyr SDK owning the first `*zephyr-*-gcc` on PATH, else None."""
    for d in filter(None, os.environ.get("PATH", "").split(os.pathsep)):
        for gcc in sorted(Path(d).glob("*zephyr-*-gcc" + (".exe" if WIN else ""))) if Path(d).is_dir() else []:
            for p in list(gcc.resolve().parents)[:4]:  # <sdk>/gnu/<tc>/bin (SDK 1.x) or <sdk>/<tc>/bin (0.x)
                if (p / "sdk_version").is_file():
                    return p
    return None


def _has_toolchain(sdk, tc):
    return any(d.name.startswith(tc) for sub in (sdk, sdk / "gnu") if sub.is_dir() for d in sub.iterdir() if d.is_dir())


def find_sdk(arch):
    """-> (sdk_dir, version) from PATH holding this arch's toolchain, (None, None) if not needed, or (False, toolchain)."""
    tc = SDK_TOOLCHAIN.get(arch, arch)
    if tc is None:
        return None, None
    sdk = sdk_from_path()
    if sdk and _has_toolchain(sdk, tc):
        return sdk, (sdk / "sdk_version").read_text().strip()
    return False, tc


def sdk_hint(tc):
    """One-line fix for a missing SDK. Points at an SDK already on disk if there is one; never installs."""
    sdk = sdk_from_path()
    if sdk:
        return f"Zephyr SDK {sdk} (from PATH) has no {tc} toolchain: add it yourself with {sdk}/setup.sh -t {tc}"
    bases = [Path(os.environ["ZEPHYR_SDK_INSTALL_DIR"]).expanduser()] if os.environ.get("ZEPHYR_SDK_INSTALL_DIR") else []
    bases += [Path.home(), Path.home() / ".local", Path.home() / ".local/opt", Path("/opt"), Path("/usr/local")]
    for base in bases:
        for cand in [base, *base.glob("zephyr-sdk-*"), *base.glob("zephyr-sdk-*/zephyr-sdk-*")]:
            bins = [*cand.glob(f"gnu/{tc}*/bin"), *cand.glob(f"{tc}*/bin")] if (cand / "sdk_version").is_file() else []
            if bins:
                return f"Zephyr SDK not on PATH (the skill doesn't install it). Found {cand}: {path_fix(bins[0])}"
    return (f"Zephyr SDK ({tc}) not on PATH. The skill doesn't ship or install it: install it yourself ({SDK_DOCS}), "
            f"then {path_fix(Path('<sdk>', 'gnu', tc, 'bin'))} (SDK 0.x: <sdk>/{tc}/bin)")


def path_fix(d):
    """How to put directory d on PATH for good, in the user's shell."""
    if WIN:  # user PATH via PowerShell; setx would truncate PATH at 1024 chars
        return (f"run in PowerShell: [Environment]::SetEnvironmentVariable('Path', '{d};' + "
                "[Environment]::GetEnvironmentVariable('Path', 'User'), 'User')  then open a new terminal")
    return f"export PATH=\"{d}:$PATH\" (add it to your shell rc)"


def setup(prof, args):
    """Board in the profile -> working build: scaffold, manifest allowlist, west init/update, deps, SDK, build."""
    nobuild = "--no-build" in args
    if prof["platform"] != "zephyr":
        print("embsk setup manages west workspaces (Zephyr). Bare metal: embsk scaffold + embsk verify.")
        return 2
    app = prof["app_dir"] or "app"
    if app in (".", "./"):
        print("west needs the manifest repo in a subfolder: embsk set app_dir=app (and move the app there)")
        return 2
    r, ws = root(), west_ws()
    foreign = ws is not None and ws["top"] != r
    print(f"== 1/6 project  {r}  (app: {app}/, board: {prof['board'] or '<none>'})")
    if not (r / app / "CMakeLists.txt").exists():
        main(["scaffold"])
    if foreign:
        print(f"== 2/6 using the existing west workspace {ws['top']} (manifest {ws['manifest']}); its manifest is not changed")
    else:
        print("== 2/6 manifest  name-allowlist = only the modules this board needs")
        ref = zephyr_base(prof)
        mods, notes = required_modules(prof, ref) if ref and prof["board"] else (None, ["no Zephyr tree yet: fetching Zephyr first"])
        if mods is None and ref and prof["board"]:
            print(f"  !! {notes[0]} — check the board name (embsk boards <mcu>)")
            return 1
        write_manifest(prof, mods or [])
        print(f"  {manifest_file(prof).relative_to(r)}: zephyr {prof.get('zephyr_rev')} + [{', '.join(mods or [])}]")
        for n in notes:
            print(f"  note: {n}")
        env = ensure_python(prof)
        env.pop("ZEPHYR_BASE", None)  # init/update must target THIS folder, never a global ZEPHYR_BASE workspace
        print("== 3/6 west init + update (shallow: --narrow, depth 1)")
        if ws is None:
            sh(["west", "init", "-l", app], env)
        sh(["west", "update", "--narrow", "-o=--depth=1"], env)
        zpath = subprocess.run(resolve(["west", "list", "-f", "{path}", "zephyr"], env), cwd=r, env=env, capture_output=True, text=True).stdout.strip()
        if zpath:
            sh(["west", "config", "--local", "zephyr.base", zpath], env)
        zb = west_ws()["zephyr"]
        mods2, notes2 = required_modules(prof, zb)
        if mods2 is None:
            print(f"  !! {notes2[0]}. Closest: {', '.join(b['id'] for b in search(board_index({**prof, 'zephyr_base': str(zb)}), prof['board'].split('/')[0])[:5])}")
            return 1
        if mods2 != mods and write_manifest(prof, mods2):
            print(f"  allowlist corrected from the fetched tree: [{', '.join(mods2)}]")
            sh(["west", "update", "--narrow", "-o=--depth=1"], env)
        for m in mods2:
            mf = next((zb.parent / "modules").rglob(f"{m.removeprefix('hal_')}/zephyr/module.yml"), None) if (zb.parent / "modules").exists() else None
            if mf and "blobs:" in mf.read_text(errors="ignore"):
                print(f"  note: {m} ships binary blobs; if the build asks for them: west blobs fetch {m}")
    zb = zephyr_base(prof)
    print("== 4/6 python deps")
    env = ensure_python(prof, zb)
    print(f"  ok  west: {shutil.which('west', path=env['PATH'])}  python: {west_python(env)}")
    print("== 5/6 toolchain (Zephyr SDK: user-installed, taken from PATH)")
    hits = find_board(board_index(prof), prof["board"])
    arch = hits[0]["arch"] if hits else "arm"
    sdk, ver = find_sdk(arch)
    if sdk is False:
        print(f"  !! {sdk_hint(ver)}")
        return 3
    print(f"  ok  {'host toolchain (no SDK needed)' if sdk is None else f'Zephyr SDK {ver} at {sdk} (from PATH)'}")
    if nobuild:
        print("== 6/6 build skipped (--no-build)")
        return 0
    print("== 6/6 build")
    rc = sh(["west", "build", "-b", prof["board"], "-p", "auto", "-d", "build", app], env, check=False)
    if rc == 0:
        print(f"setup done: {prof['board']} builds. Next: flash with `west flash -d build` (asks first), or describe the feature to build.")
    return rc


