def render(prof):
    r = root()
    f = r / "AGENTS.md"
    old = f.read_text() if f.exists() else f"# {r.name} — agent rules\n\n"
    new = re.sub(re.escape(BEGIN.split(" (")[0]) + r"[\s\S]*?" + re.escape(END) + r"\n?", "", old).rstrip() + "\n\n" + block(prof)
    f.write_text(new)
    claude = r / "CLAUDE.md"
    if not claude.exists():
        claude.write_text("@AGENTS.md\n")
    elif "AGENTS.md" not in claude.read_text():
        print("note: CLAUDE.md exists without '@AGENTS.md' — add that line so Claude Code sees the profile", file=sys.stderr)
    (r / "artifacts").mkdir(exist_ok=True)
    return f


