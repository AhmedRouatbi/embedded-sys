def root():
    p = Path.cwd()
    for d in [p, *p.parents]:
        if (d / ".embsk").is_dir():
            return d
    try:
        r = subprocess.run(["git", "rev-parse", "--show-toplevel"], capture_output=True, text=True)
    except OSError:  # git not installed
        return p
    return Path(r.stdout.strip()) if r.returncode == 0 else p


def load():
    f = root() / ".embsk" / "profile.json"
    prof = dict(DEFAULTS)
    if f.exists():
        prof.update(json.loads(f.read_text()))
    return prof


def save(prof):
    d = root() / ".embsk"
    d.mkdir(exist_ok=True)
    (d / "profile.json").write_text(json.dumps(prof, indent=2) + "\n")


def normalize(prof):
    """Keep dependent defaults consistent after platform/safety changes."""
    z = prof["platform"] == "zephyr"
    if z and prof["toolchain"] not in ("zephyr-sdk", "llvm"):
        prof["toolchain"] = "zephyr-sdk"
    if not z and prof["toolchain"] == "zephyr-sdk":
        prof["toolchain"] = "gnu-arm"
    if not z and prof["tests"] == "ztest":
        prof["tests"] = "unity"
    if prof["safety"] == "none":
        prof["safety_level"] = "-"
    elif prof["safety_level"] not in LEVELS[prof["safety"]]:
        prof["safety_level"] = LEVELS[prof["safety"]][min(1, len(LEVELS[prof["safety"]]) - 1)]
    return prof


def visible(prof, when):
    return not when or all(prof.get(k) in v for k, v in when.items())


def coerce(key, raw):
    t = next(o[2] for o in OPTIONS if o[1] == key)
    if t in ("multi", "list"):
        return [x.strip() for x in raw.split(",") if x.strip()]
    if t == "bool":
        return raw.lower() in ("1", "true", "yes", "on", "y")
    return raw


